/* --------------------------------------------------------- emit demoSeed */

const ts = `// AUTO-GENERATED by scripts/generate-seed.mjs — do not edit by hand.
// Run \`npm run seed\` after changing scripts/catalog.mjs or adding images.
import type { BlogPost, Category, Product, Review } from './supabase';

export const seedCategories: Category[] = ${JSON.stringify(cats, null, 2)};

export const seedProducts: Product[] = ${JSON.stringify(products, null, 2)};

export const seedBlogPosts: BlogPost[] = ${JSON.stringify(blogPosts, null, 2)};

export const seedReviews: Review[] = ${JSON.stringify(reviews, null, 2)};
`;
fs.writeFileSync(path.join(root, 'src/lib/demoSeed.ts'), ts);

/* ------------------------------------------------------------- emit SQL */

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

const sql = `/*
# Re-seed catalogue (auto-generated by scripts/generate-seed.mjs)

Replaces categories, products, blog posts and reviews with the full catalogue
(${products.length} products across ${cats.length} categories). Product images live in
public/images/<category>/<slug>.jpg.
*/

DELETE FROM order_items;
DELETE FROM orders;
DELETE FROM cart_items;
DELETE FROM reviews;
DELETE FROM products;
DELETE FROM blog_posts;
DELETE FROM categories;

INSERT INTO categories (name, slug, icon) VALUES
${cats.map((c) => `  (${q(c.name)}, ${q(c.slug)}, ${q(c.icon)})`).join(',\n')}
ON CONFLICT (slug) DO NOTHING;

INSERT INTO products (name, slug, description, price, image_url, category_id, rating, stock) VALUES
${products
  .map(
    (p) =>
      `  (${q(p.name)}, ${q(p.slug)}, ${q(p.description)}, ${p.price}, ${q(p.image_url)}, (SELECT id FROM categories WHERE slug=${q(
        p.category_id.replace('cat-', ''),
      )}), ${p.rating}, ${p.stock})`,
  )
  .join(',\n')}
ON CONFLICT (slug) DO NOTHING;

INSERT INTO blog_posts (title, slug, excerpt, content, image_url, author) VALUES
${blogPosts
  .map((b) => `  (${q(b.title)}, ${q(b.slug)}, ${q(b.excerpt)}, ${q(b.content)}, ${q(b.image_url)}, ${q(b.author)})`)
  .join(',\n')}
ON CONFLICT (slug) DO NOTHING;

INSERT INTO reviews (product_id, name, rating, comment) VALUES
${reviews
  .map(
    (r) =>
      `  ((SELECT id FROM products WHERE slug=${q(r.product_id.replace('prod-', ''))}), ${q(r.name)}, ${r.rating}, ${q(
        r.comment,
      )})`,
  )
  .join(',\n')}
ON CONFLICT DO NOTHING;
`;
fs.writeFileSync(path.join(root, 'supabase/migrations/20260820120000_reseed_full_catalog.sql'), sql);

