/*
 * Regenerates src/lib/demoSeed.ts and supabase/migrations/<ts>_reseed_catalog.sql
 * from scripts/catalog.mjs.
 *
 * Only products whose image file actually exists in public/images/<category>/
 * are emitted, so the catalogue can grow as artwork is added.
 *
 * Usage: npm run seed
 */
import fs from 'fs';
import path from 'path';
import { catalog, categories } from './catalog.mjs';

const root = path.resolve(import.meta.dirname, '..');
const now = Date.now();
const iso = (daysAgo) => new Date(now - daysAgo * 86400000).toISOString();

/* ------------------------------------------------------------- gather -- */

const missing = [];
const products = [];

catalog.forEach((p, i) => {
  const rel = `/images/${p.cat}/${p.slug}.jpg`;
  if (!fs.existsSync(path.join(root, 'public', rel))) {
    missing.push(rel);
    return;
  }
  products.push({
    id: `prod-${p.slug}`,
    name: p.name,
    slug: p.slug,
    description: p.desc,
    price: p.price,
    image_url: rel,
    category_id: `cat-${p.cat}`,
    rating: p.rating,
    stock: p.stock,
    created_at: iso(120 - i),
  });
});

const cats = categories.map((c, i) => ({
  id: `cat-${c.slug}`,
  name: c.name,
  slug: c.slug,
  icon: c.icon,
  created_at: iso(200 - i),
}));

